"""Regenerate ``src/botwithus/api/_action_bar_ids.py`` from a gameval dump.

The Java host resolves the action-bar slot variables by gameval name at run time
(``ACTIONBAR<bar>_INT<slot>_TYPE`` / ``_ID`` varbits, ``ACTIONBAR<bar>_OBJ<slot>`` varps and
``TOPLEVEL_V2_COMBAT_BAR__GRAPHIC_<slot>`` components). The native host exposes no gameval index
to the Python frontend, and the ids follow no arithmetic pattern, so the frontend carries them as
a table generated by this script.

Usage::

    python tools/gamevals/gen_action_bar_ids.py <gameval dump dir>

``<gameval dump dir>`` holds NXTCache's per-type gameval JSON (``varbit.json``,
``var_player.json``, ``component.json``), as ``nxtcache-dumper`` writes it.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

BARS = 18
SLOTS = 14
OUT = Path(__file__).resolve().parents[2] / "src" / "botwithus" / "api" / "_action_bar_ids.py"


def _index(path: Path) -> dict[str, int]:
    entries = json.loads(path.read_text(encoding="utf-8"))["entries"]
    return {name: int(key) for key, name in entries.items()}


def main(dump: Path) -> None:
    varbits = _index(dump / "varbit.json")
    varps = _index(dump / "var_player.json")
    components = _index(dump / "component.json")
    rows = []
    for bar in range(1, BARS + 1):
        slots = []
        for slot in range(1, SLOTS + 1):
            base = f"ACTIONBAR{bar}_INT{slot}"
            slots.append((varbits[base + "_TYPE"], varbits[base + "_ID"],
                          varps[f"ACTIONBAR{bar}_OBJ{slot}"]))
        rows.append(slots)
    buttons = [components[f"TOPLEVEL_V2_COMBAT_BAR__GRAPHIC_{s}"] for s in range(1, SLOTS + 1)]
    lines = [
        '"""GENERATED by tools/gamevals/gen_action_bar_ids.py -- do not edit by hand.',
        "",
        "Action-bar slot variables by bar (1..18) and slot (1..14), and the slot buttons, resolved",
        "from the gameval names the Java host uses (see that script).",
        '"""',
        "",
        "# SLOT_VARS[bar - 1][slot - 1] = (type varbit, id varbit, item varp)",
        "SLOT_VARS: tuple[tuple[tuple[int, int, int], ...], ...] = (",
    ]
    for bar, slots in enumerate(rows, start=1):
        lines.append(f"    (  # ACTIONBAR{bar}")
        for i in range(0, SLOTS, 4):
            chunk = ", ".join(f"({t}, {d}, {o})" for t, d, o in slots[i:i + 4])
            lines.append(f"        {chunk},")
        lines.append("    ),")
    lines.append(")")
    lines.append("")
    lines.append("# SLOT_BUTTONS[slot - 1] = packed TOPLEVEL_V2_COMBAT_BAR__GRAPHIC_<slot>")
    lines.append("SLOT_BUTTONS: tuple[int, ...] = (")
    for i in range(0, SLOTS, 7):
        lines.append("    " + ", ".join(str(b) for b in buttons[i:i + 7]) + ",")
    lines.append(")")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(Path(sys.argv[1]))
